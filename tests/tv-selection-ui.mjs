import assert from "node:assert/strict";
import { chromium } from "playwright-core";

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox"] });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  const writes = [];
  let fail = false;
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/api/media?*", (route) => route.fulfill({ json: { items: [], mode: "demo" } }));
  await page.route("**/api/users", (route) => route.fulfill({ json: { users: [{ id: "demo", role: "ADMIN", name: "Demo", accessRules: [] }] } }));
  await page.route("**/api/taxonomy", (route) => route.fulfill({ json: { people: [], tags: [], groups: [] } }));
  await page.route("**/api/media/tv-selection", (route) => {
    const body = route.request().postDataJSON();
    writes.push(body);
    return route.fulfill(fail ? { status: 403, json: { error: "Permessi di modifica richiesti" } } : { json: { ...body, mode: "demo" } });
  });
  await page.goto(process.env.FRAMEO_TEST_URL ?? "http://localhost:3102");
  await page.locator(".media-card").first().click();
  const toggle = page.getByRole("switch", { name: "Mostra nella Galleria TV", exact: true });
  await toggle.waitFor();
  assert.equal(await toggle.getAttribute("aria-checked"), "false");
  await toggle.click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Mostra nella Galleria TV"]')?.getAttribute("aria-checked") === "true");
  assert.equal(writes.at(-1).showOnTv, true);
  assert.equal(await page.locator('.media-card .media-tv-badge').count(), 1);
  fail = true;
  await toggle.click();
  await page.getByText("Permessi di modifica richiesti", { exact: true }).waitFor();
  assert.equal(await toggle.getAttribute("aria-checked"), "true");
  fail = false;
  await page.getByRole("button", { name: "Chiudi dettagli", exact: true }).click();
  await page.locator(".media-card .select-control").nth(0).click();
  await page.locator(".media-card .select-control").nth(1).click();
  await page.getByRole("button", { name: "Aggiungi alla TV", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".bulk-tv-actions button")?.disabled === true);
  assert.equal(writes.at(-1).mediaIds.length, 2);
  assert.equal(await page.locator('.media-card .media-tv-badge').count(), 2);
  assert.equal(writes.at(-1).showOnTv, true);
  await page.setViewportSize({ width: 390, height: 844 });
  const remove = page.getByRole("button", { name: "Rimuovi dalla TV", exact: true });
  const box = await remove.boundingBox();
  assert.ok(box && box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844);
  await page.screenshot({ path: "/tmp/frameo-tv-selection-mobile.png" });
  const tvPage = await page.context().newPage();
  await tvPage.route("**/api/media?*", (route) => route.fulfill({ json: { items: [], mode: "demo" } }));
  await tvPage.goto(`${process.env.FRAMEO_TEST_URL ?? "http://localhost:3102"}/tv`);
  await tvPage.locator("[data-tv-card]").first().waitFor();
  assert.equal(await tvPage.locator("[data-tv-card]").count(), 2);
  await tvPage.reload();
  await tvPage.locator("[data-tv-card]").first().waitFor();
  assert.equal(await tvPage.locator("[data-tv-card]").count(), 2);
  await remove.click();
  await page.waitForFunction(() => document.querySelector(".bulk-tv-actions button:last-child")?.disabled === true);
  assert.equal(writes.at(-1).showOnTv, false);
  assert.equal(await page.locator('.media-card .media-tv-badge').count(), 0);
  await tvPage.getByText("La Galleria TV è vuota.", { exact: false }).waitFor();
  assert.equal(await tvPage.locator("[data-tv-card]").count(), 0);
  assert.deepEqual(errors, []);
  console.log("TV selection UI: individual/bulk selection, failed saves, mobile controls and demo persistence/sync/filtering passed.");
} finally { await browser.close(); }
